"""Verify every hand-typed figure in the write-up against the run artifacts.

Generated tables are handled by `sibyl tables`. This checks the numbers that
live in PROSE, which generation cannot reach. Run it after any re-run:

    uv run python research/check_figures.py

It exists because two figures in earlier drafts were wrong: an invented
walk-forward table (caught by hand) and an event count of 1,017 that belonged
to the whole resolved universe rather than the fitted subset of 608 (caught by
this script). For a document whose only value is honest reporting, a figure
nobody can re-derive is a liability.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DOC = ROOT / "phase3-findings.md"


def main() -> int:
    doc = DOC.read_text(encoding="utf-8")
    cal = json.loads((ROOT / "calibration.json").read_text(encoding="utf-8"))
    pw = json.loads((ROOT / "power.json").read_text(encoding="utf-8"))

    rates = {c["true_slope"]: c["detection_rate"] for c in pw["conditions"]}
    null_rate = next(c["detection_rate"] for c in pw["conditions"] if c["is_null"])
    improvements = [f["improvement"] for f in cal["folds"]]
    tradeable = sum(1 for c in cal["cells"] if c["tradeable"])

    # (label, string that must appear in the doc, value it must equal)
    checks: list[tuple[str, str, bool]] = [
        ("row count", f"{cal['n_rows']:,}", True),
        ("market count", f"{cal['n_markets']:,}", True),
        ("event count", f"{cal['n_clusters']:,}", True),
        ("cell count", str(cal["n_cells"]), True),
        ("cells with an interval", str(cal["n_cells_with_ci"]), True),
        ("in-sample mu", f"{cal['mu']:.3f}", True),
        ("tradeable cells", str(tradeable), True),
        ("mean improvement", f"{cal['mean_improvement']:.4f}".lstrip("-"), True),
        ("noise sd", f"{pw['noise_sd']:.3f}", True),
        ("null false-positive rate", f"{null_rate:.1%}".rstrip("%"), True),
        ("smallest detectable slope", f"{pw['smallest_detectable']:.2f}", True),
        ("worst fold", f"{min(improvements):.3f}".lstrip("-"), True),
        ("best fold", f"{max(improvements):.3f}", True),
    ]

    failures: list[str] = []
    for label, needle, must_appear in checks:
        present = needle in doc
        status = "OK  " if present == must_appear else "FAIL"
        if present != must_appear:
            failures.append(f"{label}: expected {needle!r} in the document")
        print(f"{status} {label:<28} {needle}")

    # The generated blocks must actually have been generated.
    for name in ("walkforward", "tradeable", "borrowed", "reliability", "power"):
        marker = f"<!-- BEGIN:{name} -->"
        if marker not in doc:
            failures.append(f"missing marker block: {name}")
            continue
        body = doc.split(marker, 1)[1].split(f"<!-- END:{name} -->", 1)[0]
        if "generated by" not in body:
            failures.append(f"block {name} is not generated — run `sibyl tables`")
        print(f"{'OK  ' if 'generated by' in body else 'FAIL'} block:{name:<22} generated")

    # No stale "1,017 events" claim about the fitted data.
    if re.search(r"1,977 resolved markets / 1,017 events", doc):
        failures.append("event count for the FIT must be n_clusters, not the ledger total")

    print()
    if failures:
        print(f"{len(failures)} PROBLEM(S):")
        for f in failures:
            print(f"  - {f}")
        return 1
    print(f"all {len(checks)} prose figures and 5 generated blocks verified")
    return 0


if __name__ == "__main__":
    sys.exit(main())
