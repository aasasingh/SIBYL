"""Generate the write-up's numeric tables from the run artifacts.

This module exists because of a near-miss: the first draft of
`phase3-findings.md` contained a hand-typed walk-forward table whose numbers
were invented, and it was corrected only because the figures were checked
against the report afterwards. For a document whose entire value is that it
reports a negative result honestly, one fabricated number would discredit all
of it.

So no number in the findings doc is typed. `sibyl calibrate --json-out` and
`sibyl power --json-out` write structured artifacts, and `sibyl tables`
renders Markdown from them and injects it into the document between markers:

    <!-- BEGIN:walkforward -->   ... generated ...   <!-- END:walkforward -->

Prose stays hand-written. Tables are generated, and regenerating them is how
the document gets updated after a re-run.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

MARKER_BEGIN = "<!-- BEGIN:{name} -->"
MARKER_END = "<!-- END:{name} -->"

GENERATED_NOTE = "<!-- generated by `sibyl tables`; do not edit by hand -->"


def _fmt(value: Any, spec: str = "") -> str:
    if value is None:
        return "—"
    if isinstance(value, float):
        return format(value, spec) if spec else f"{value:g}"
    return str(value)


def render_walkforward(data: dict[str, Any]) -> str:
    folds = data.get("folds", [])
    if not folds:
        return "_No folds: too few events spread over time._"
    lines = [
        "| fold | train markets | test markets | train events | test events "
        "| Brier (model) | Brier (raw price) | improvement |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for f in folds:
        improvement = f["improvement"]
        shown = f"**{improvement:+.6f}**" if improvement < 0 else f"{improvement:+.6f}"
        lines.append(
            f"| {f['fold']} | {f['train_markets']} | {f['test_markets']} "
            f"| {f['train_clusters']} | {f['test_clusters']} "
            f"| {f['brier_model']:.6f} | {f['brier_baseline']:.6f} | {shown} |"
        )
    mean = data["mean_improvement"]
    positive = data["folds_positive"]
    lines += [
        "",
        f"Mean improvement **{mean:+.6f}**, positive in **{positive} of {len(folds)}** folds.",
    ]
    return "\n".join(lines)


def render_tradeable(data: dict[str, Any]) -> str:
    cells = [c for c in data.get("cells", []) if c["tradeable"]]
    if not cells:
        return "_No cell shows a demonstrated cell-specific edge._"
    lines = [
        "| cell | b traded | shrinkage | direction |",
        "|---|---|---|---|",
    ]
    for c in sorted(cells, key=lambda c: -abs(c["effective_slope"] - 1.0)):
        direction = "compressed" if c["effective_slope"] > 1 else "over-extended"
        shrink = _fmt(c.get("shrinkage"), ".2f")
        lines.append(
            f"| {c['domain']}/{c['horizon']} | {c['effective_slope']:.3f} "
            f"| {shrink} | {direction} |"
        )
    lines += [
        "",
        f"**{len(cells)} of {data['n_cells_with_ci']}** cells with an interval clear the "
        f"bar, against **{data['expected_false_positives']:.1f}** expected by chance "
        "at 95% confidence.",
    ]
    return "\n".join(lines)


def render_borrowed(data: dict[str, Any]) -> str:
    rows = [
        c
        for c in data.get("cells", [])
        if not c["tradeable"] and str(c.get("gating_note", "")).startswith("shrinkage")
    ]
    if not rows:
        return "_No cell was rejected for borrowed signal._"
    lines = ["| cell | own b | b actually traded | shrinkage |", "|---|---|---|---|"]
    for c in sorted(rows, key=lambda c: -(c.get("shrinkage") or 0)):
        lines.append(
            f"| {c['domain']}/{c['horizon']} | {c['slope']:.3f} "
            f"| {c['effective_slope']:.3f} | {c['shrinkage']:.2f} |"
        )
    return "\n".join(lines)


def render_reliability(data: dict[str, Any]) -> str:
    bins = data.get("reliability", [])
    if not bins:
        return "_No reliability bins._"
    lines = [
        "| price bin | mean price | gap (row-level) | gap (market-level) | rows | markets |",
        "|---|---|---|---|---|---|",
    ]
    for b in bins:
        row_gap = b["gap_row"]
        mkt_gap = b["gap_market"]
        # Bold the mid-range contrast: it is the point of the table.
        emphasise = 0.3 <= b["bin_mid"] <= 0.7
        rg = f"**{row_gap:+.4f}**" if emphasise else f"{row_gap:+.4f}"
        mg = f"**{mkt_gap:+.4f}**" if emphasise else f"{mkt_gap:+.4f}"
        lines.append(
            f"| {b['bin_mid']:.2f} | {b['mean_price']:.4f} | {rg} | {mg} "
            f"| {b['n_rows']} | {b['n_markets']} |"
        )
    return "\n".join(lines)


def render_power(data: dict[str, Any]) -> str:
    rows = data.get("conditions", [])
    if not rows:
        return "_No power conditions._"
    lines = [
        "| true b | fitted b | mean improvement | detection rate | verdict |",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        rate = r["detection_rate"]
        label = "**false positive rate**" if r["is_null"] else "detection"
        verdict = (
            "null — this is the floor"
            if r["is_null"]
            else ("detected" if rate >= 0.8 else "**undetectable**")
        )
        lines.append(
            f"| {r['true_slope']:.1f} | {r['mean_fitted_slope']:.3f} "
            f"| {r['mean_improvement']:+.6f} | {rate:.1%} ({label}) | {verdict} |"
        )
    smallest = data.get("smallest_detectable")
    lines += [
        "",
        f"{data['n_seeds']} seeds per condition, {data['n_folds']} folds, logit-space "
        f"noise sd {data['noise_sd']:.3f}.",
        "Smallest slope reaching "
        f"{data['threshold']:.0%} power: "
        + (f"**b = {smallest:.2f}**" if smallest is not None else "**none tested**"),
    ]
    return "\n".join(lines)


RENDERERS = {
    "walkforward": ("calibration", render_walkforward),
    "tradeable": ("calibration", render_tradeable),
    "borrowed": ("calibration", render_borrowed),
    "reliability": ("calibration", render_reliability),
    "power": ("power", render_power),
}


def inject(document: Path, artifacts: dict[str, dict[str, Any]]) -> list[str]:
    """Replace every marked block in `document`. Returns the names updated."""
    text = document.read_text(encoding="utf-8")
    updated: list[str] = []
    for name, (source, renderer) in RENDERERS.items():
        begin, end = MARKER_BEGIN.format(name=name), MARKER_END.format(name=name)
        if begin not in text or end not in text:
            continue
        data = artifacts.get(source)
        if data is None:
            continue
        start = text.index(begin) + len(begin)
        stop = text.index(end)
        body = f"\n{GENERATED_NOTE}\n{renderer(data)}\n"
        text = text[:start] + body + text[stop:]
        updated.append(name)
    document.write_text(text, encoding="utf-8")
    return updated


def load_artifact(path: Path) -> dict[str, Any]:
    loaded = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(loaded, dict):
        raise TypeError(f"{path} does not contain a JSON object")
    return loaded
